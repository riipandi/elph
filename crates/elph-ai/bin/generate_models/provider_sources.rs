//! Elph provider ↔ models.dev key mapping and factory defaults.

/// Metadata for one Elph chat provider.
#[derive(Debug, Clone)]
pub struct ProviderSource {
    pub id: &'static str,
    /// models.dev provider keys to try (first hit wins for listing).
    pub models_dev_keys: &'static [&'static str],
    pub default_api: &'static str,
    pub default_base_url: &'static str,
    /// When true, keep existing catalog model *ids* (gateway routes) and enrich from models.dev.
    pub gateway_preserve_ids: bool,
    /// Optional public base URL for live pricing probes (OpenAI-compatible `/models`).
    pub live_pricing_base: Option<&'static str>,
    pub live_pricing_env: Option<&'static str>,
}

